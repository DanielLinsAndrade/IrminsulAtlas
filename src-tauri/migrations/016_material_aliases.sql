CREATE TEMP TABLE resolved_inventory_016 AS
SELECT i.*, a.canonical_id FROM inventory_items i
JOIN material_aliases_016 a ON a.alias_key =
replace(replace(replace(lower(CASE
 WHEN lower(i.material_id) LIKE 'material_%' THEN substr(i.material_id,10)
 WHEN lower(i.material_id) LIKE 'mat_%' THEN substr(i.material_id,5)
 ELSE i.material_id END), '_', ''), '-', ''), ' ', '');
CREATE TEMP TABLE affected_inventory_016 AS
SELECT profile_id, canonical_id FROM resolved_inventory_016
GROUP BY profile_id, canonical_id HAVING COUNT(*) > 1 OR MAX(material_id <> canonical_id) = 1;
INSERT OR IGNORE INTO inventory_alias_backup (migration_id,payload)
SELECT '016_material_aliases', COALESCE(json_group_array(json_object('profileId',r.profile_id,'materialId',r.material_id,'quantity',r.quantity,'updatedAt',r.updated_at)), '[]')
FROM resolved_inventory_016 r JOIN affected_inventory_016 a USING(profile_id,canonical_id);
CREATE TEMP TABLE merged_inventory_016 AS
SELECT r.profile_id,r.canonical_id AS material_id,SUM(r.quantity) AS quantity,MAX(r.updated_at) AS updated_at
FROM resolved_inventory_016 r JOIN affected_inventory_016 a USING(profile_id,canonical_id)
GROUP BY r.profile_id,r.canonical_id;
DELETE FROM inventory_items WHERE EXISTS (
 SELECT 1 FROM resolved_inventory_016 r JOIN affected_inventory_016 a USING(profile_id,canonical_id)
 WHERE r.profile_id=inventory_items.profile_id AND r.material_id=inventory_items.material_id
);
INSERT INTO inventory_items(profile_id,material_id,quantity,updated_at)
SELECT profile_id,material_id,quantity,updated_at FROM merged_inventory_016;
DROP TABLE merged_inventory_016;
DROP TABLE affected_inventory_016;
DROP TABLE resolved_inventory_016;
DROP TABLE material_aliases_016;
